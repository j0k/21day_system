"""Данные трёх 21-дневных систем микро-практики.

Каждая система: id, название, подзаголовок, три недели и 21 день
(минуты, действие, что качается).
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Day:
    n: int
    minutes: int
    action: str
    skill: str


@dataclass(frozen=True)
class Week:
    n: int
    title: str
    accent: str
    days: list[Day]


@dataclass(frozen=True)
class System:
    id: str
    title: str
    subtitle: str
    emoji: str
    weeks: list[Week] = field(default_factory=list)

    @property
    def days(self) -> list[Day]:
        return [d for w in self.weeks for d in w.days]

    def day(self, n: int) -> Day:
        for d in self.days:
            if d.n == n:
                return d
        raise KeyError(n)

    def week_of(self, n: int) -> Week:
        for w in self.weeks:
            if any(d.n == n for d in w.days):
                return w
        raise KeyError(n)


def _week(n, title, accent, rows):
    base = (n - 1) * 7
    return Week(n, title, accent,
                [Day(base + i + 1, m, a, s)
                 for i, (m, a, s) in enumerate(rows)])


